#!/usr/bin/env python3
"""Independent MCF2 vectors using Python's standard library, not Mirror code.
Synthetic public keys correspond to the published [1;32] and [2;32] test seeds.
Print the fixture, or --check it against the committed Rust-test fixture.
"""
import hashlib
import struct
import sys
from pathlib import Path


def digest(value: bytes) -> bytes:
    return hashlib.sha256(hashlib.sha256(value).digest()).digest()


def generate() -> str:
    keys = [
        bytes.fromhex('8a88e3dd7409f195fd52db2d3cba5d72ca6709bf1d94121bf3748801b40f6f5c'),
        bytes.fromhex('8139770ea87d175f56a35466c34c7ecccb8d8a91b4ee37a25df60f5b8fc9b394'),
    ]
    descriptors = [keys[i] + bytes([0x31 + i]) * 32 + bytes([0x41 + i]) * 32 for i in range(2)]
    limits = [1048576, 256, 256, 64, 1024, 1024, 65536, 65536, 1000, 4194304]
    encoded = b'MCF2' + struct.pack('<HH', 2, 1) + bytes([0x11]) * 32
    encoded += struct.pack('<IQH', 0x1f0fffff, 1800000000, 2) + bytes([0x22]) * 32
    encoded += struct.pack('<10IQQ', *limits, 32, 256)
    encoded += struct.pack('<I', len(descriptors)) + b''.join(descriptors)
    encoded += struct.pack('<I', 2)
    encoded += bytes([0x51]) * 32 + struct.pack('<Q', 0)
    encoded += bytes([0x52]) * 32 + struct.pack('<Q', 123456789)
    assert len(encoded) == 422
    context = digest(b'MIRROR_CONFIG_V2' + encoded)
    lines = ['# Independent synthetic MCF2 fixture. Generated by tools/reference_config_v2.py.',
             f'config_hex={encoded.hex()}', f'context={context.hex()}']
    for index, descriptor in enumerate(descriptors):
        tail = context + struct.pack('<I', index) + descriptor
        lines.append(f'seed{index}_hash={digest(b"MIRROR_SEED_V2" + tail).hex()}')
        lines.append(f'seed{index}_id={digest(b"MIRROR_SEED_ID_V2" + tail).hex()}')
    return '\n'.join(lines) + '\n'


def main() -> None:
    expected = generate()
    if sys.argv[1:] == ['--check']:
        path = Path(__file__).resolve().parents[1] / 'crates/mirror-personhood/tests/vectors/config_v2.txt'
        if path.read_text(encoding='utf-8') != expected:
            raise SystemExit('MCF2 reference fixture differs; investigate, do not bless a failing Rust output.')
        print('Independent MCF2 configuration/seed vectors: PASS')
    elif not sys.argv[1:]:
        print(expected, end='')
    else:
        raise SystemExit('usage: reference_config_v2.py [--check]')


if __name__ == '__main__':
    main()
